package org.example.e09generics;

public class Box<T> {
    public T arr;
    //T라고 적혀져있는 내부에 인트배열로 만들어짐
    // public int[] arr = new int[5];
    //배열은 int[]든 String[]이든 언어 자체에 내장된 특별한 객체 타입이라서 따로 클래스 파일이 필요 없는 것
    //길이 5인 배열을 만듦
    //관습적으로 대문자 한문자를 사용함 실제용어의 약어들
    //컴파일 할 때 이 T가 오브젝트로 치환이 되어서 컴파일 됨
    //자바에서 만드는 모든 인스턴스들은 최상위의 오브젝트를 상속하는거임.
    //기본형은 애초에 클래스가 아니기때문에 상속이 안됨

    //생성자, 일반, 디스트로이어 메소드
    //생성자 메서드의 주요 역할 - 객체의 초기화 할 때 초기값을 설정하기 위한 용도로 많이 쓴다.
    //디폴트 생성자 - 구현부에 아무런 연산이 없는(파라미터도 없) 기본적으로 생성되는 생성자임.
    public Box(T arr) {
        this.arr = arr;
        //int[]는 외부에서 받아옴
    }
}
